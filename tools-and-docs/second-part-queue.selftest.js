'use strict';
// Бот забирает очередь второй части ЕГЭ («Проверочная») и шлёт ученику сам.
//
// 🔴 Почему забираем мы, а не они присылают: запись в наш notifyJobs
// авторизуется КАК УЧИТЕЛЬ (ctx.teacher + teacherCanSeeStudent), а сервер
// учительской сессией не обладает. Иначе пришлось бы пробивать дыру в
// авторизации боевого приложения — в том самом месте, которое 11.08.2026 уже
// оставило без уведомлений о домашке ВСЕХ, и молча.
//
// Проверяем то, чего не видно на экране: очередь на той стороне либо растёт
// вечно, либо теряет сообщения, и заметить это можно только по жалобам.
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const strip = src => src.split('\n').filter(l => !l.trim().startsWith('//')).join('\n');
const bot = strip(fs.readFileSync(path.join(root, 'server/bot/src/bot.js'), 'utf8'));

const fn = bot.slice(bot.indexOf('function watchSecondPart()'), bot.indexOf('const MAX_WAITING_AGE_MS'));
assert.ok(fn.length > 400, 'watchSecondPart не найдена');

// ── 1. Опрос вообще запускается ─────────────────────────────────────────────
assert.match(bot, /watchSecondPart\(\);/, 'Опрос очереди не запускается при старте бота');
assert.match(fn, /setInterval\(tick, SECOND_PART_POLL_MS\)/, 'Очередь опрашивается один раз, а не постоянно');

// ── 2. Без ключа не ходим ───────────────────────────────────────────────────
assert.match(fn, /if \(!SECOND_PART_HOST_KEY\)/,
  'Без ключа бот всё равно долбится в чужой сервис — в логах будет ошибка каждые 20 секунд');
assert.match(fn, /'X-Host-Key': SECOND_PART_HOST_KEY/, 'Ключ не передаётся — очередь ответит отказом');

// ── 3. Отписка уважается, но только для рассылки ────────────────────────────
// Тумблер «Домашка» гасит рассылку про задания. Личное — «работу проверили»,
// «куратор ответил», «работу вернули» — обязано доходить независимо: человек
// выключал рассылку, а не переписку с куратором, и терял ответ на свой вопрос
// молча, потому что сообщение снималось с очереди как доставленное.
assert.match(fn, /SELECT notify_hw FROM users WHERE id = \?/,
  'Флаг отписки не проверяется: выключивший «Домашку» получит её вторую половину');
assert.match(fn, /if \(SECOND_PART_BROADCAST\.has\(kind\)\) \{[\s\S]{0,200}?notify_hw/,
  'Тумблер применяется ко всему подряд — личные сообщения снова глохнут');
assert.doesNotMatch(bot, /SECOND_PART_BROADCAST = new Set\(\[[^\]]*'reviewed'/,
  'Проверка работы объявлена рассылкой — её погасит тумблер «Домашка»');
assert.doesNotMatch(bot, /SECOND_PART_BROADCAST = new Set\(\[[^\]]*'answer'/,
  'Ответ куратора объявлен рассылкой — его погасит тумблер «Домашка»');

// ── 3б. Отметка «есть новое» ставится ДО отправки ───────────────────────────
// Значок на вкладке «Домашка» считает только первую часть, и раздел второй
// выглядел одинаково — с работой и без. Отметка ставится раньше отправки
// нарочно: недоставленное сообщение не повод скрывать от ученика, что задали.
assert.match(fn, /if \(SECOND_PART_NEWS\.has\(kind\)\) await markSecondPartNews\(chatId\);[\s\S]{0,200}?const sent = await sendSafe/,
  'Отметка о новом ставится после отправки или не ставится вовсе');
assert.match(bot, /\.set\(\{ secondPartNewsAt: Date\.now\(\) \}, \{ merge: true \}\)/,
  'Отметка пишется не слиянием — снесёт выданную домашку в документе ученика');

// ── 4. Чужой текст уходит без разметки ──────────────────────────────────────
// Текст приходит из другой системы. С parse_mode одна кривая скобка роняет
// отправку, а спецсимволы дают чужое оформление.
assert.doesNotMatch(fn, /parse_mode/,
  'Чужой текст отправляется с разметкой — это чужой ввод в разметке сообщения');

// ── 5. Подтверждаем только то, что закрыто ──────────────────────────────────
assert.match(fn, /if \(sent\) \{ done\.push\(id\);/,
  'Успешная отправка не подтверждается — та сторона пришлёт это же снова, и так вечно');
assert.match(fn, /if \(isUnreachable\(chatId\)\) done\.push\(id\);/,
  'Недостижимый адресат не подтверждается — очередь на той стороне будет расти вечно на одном человеке');
// Сбой сети НЕ подтверждаем: пусть придёт снова.
const ackLine = /body: JSON\.stringify\(\{ ids: done \}\)/;
assert.match(fn, ackLine, 'Подтверждение шлётся не тем форматом, о котором договорились');

// ── 6. Ответ чужой системы не принимается на веру ───────────────────────────
assert.match(fn, /if \(!res\.ok\)/, 'Ответ не проверяется на успешность — разбирать будем текст ошибки');
assert.match(fn, /slice\(0, SECOND_PART_BATCH_CAP\)/,
  'Размер пачки не ограничен: одна большая выдача заблокирует бота на минуты');
assert.match(fn, /String\(item\?\.text \|\| ''\)\.slice\(0, 3500\)/,
  'Длина текста не ограничена — Telegram отобьёт сообщение целиком');
assert.match(fn, /Number\.isFinite\(chatId\)/, 'Адресат не проверяется на число');

// ── 7. О недоступности говорим один раз ─────────────────────────────────────
// Иначе при лежащем соседе лог растёт на три строки в минуту и топит собой всё
// остальное — ровно так у нас однажды потерялась настоящая ошибка.
//
// Путей отказа ДВА — плохой ответ и брошенное исключение, — и глушить надо оба.
// Проверять «есть хоть один глушитель» недостаточно: сняв любой из них, тест
// остался бы зелёным, а лог всё равно бы утонул.
const guards = (fn.match(/if \(!quiet\) \{ quiet = true;/g) || []).length;
assert.strictEqual(guards, 2,
  `Заглушено ${guards} путей отказа из двух — незаглушённый будет писать в лог каждые 20 секунд`);
// Сброс обязан стоять ИМЕННО после удачного ответа: объявление `let quiet = false`
// у входа в функцию этой роли не исполняет, а регулярка без привязки его засчитает.
assert.match(fn, /quiet = false;\s*\n\s*const body = await res\.json\(\)/,
  'Флаг тишины не сбрасывается после удачного ответа — о новой поломке не узнаем');

// ── 8. Выключатель второй части у учителя ───────────────────────────────────
// Признак `secondPart` у группы решает, увидит ли ученик раздел «Развёрнутые
// ответы» и уедет ли состав этой группы во вторую систему. Пока команды не
// было, включить его можно было только правкой в базе руками — то есть
// «открывать выборочно» работало лишь при живом администраторе рядом.
assert.match(bot, /bot\.command\('secondpart', doSecondPart\);/,
  'Нет команды /secondpart — включить вторую часть группе снова нечем');
assert.match(bot, /\{ command: 'secondpart'/,
  'Команда не объявлена в меню бота — учитель её не найдёт');

const toggle = bot.slice(bot.indexOf('bot.callbackQuery(/^sp:'),
                         bot.indexOf('// ---------- Настройки уведомлений'));
assert.ok(toggle.length > 200, 'Обработчик переключения не найден');

// 🔴 Владение. Без него любой учитель, зная код чужой группы, открывал бы ей
// вторую часть — а вместе с признаком в чужую систему уезжает и состав класса
// (эндпоинт отдаёт учеников только включённых групп). Это утечка, а не опечатка.
assert.match(toggle, /teacherClasses\(ctx\.from\.id\)\.find\(x => x\.code === code\)/,
  'Переключатель не проверяет, своя ли это группа');
assert.match(toggle, /if \(!own\) return ctx\.answerCallbackQuery\('Это не ваша группа'\)/,
  'Проверка владения есть, но её результат ни на что не влияет');

// Признак пишется слиянием: документ группы хранит ещё и учебные настройки
// («дошли до года», лимиты), и полная перезапись снесла бы их.
assert.match(toggle, /\{ merge: true \}/,
  'Признак пишется поверх документа группы — снесёт остальные настройки');
assert.match(toggle, /secondPart: next/,
  'Переключение не записывает новое значение');

console.log('second-part-queue.selftest: ok');
