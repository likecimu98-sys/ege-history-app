'use strict';

// 🔴 УБОРКА ВЫЗОВОВ НА ДУЭЛЬ.
//
// Жалоба 01.08.2026: «половина сообщений о дуэлях не удаляется, на втором аккаунте
// висят вызовы от меня». При этом таблица duel_msgs была ПУСТА — то есть по учёту
// бота удалять было нечего, а у людей сообщения висели.
//
// Разобрали два дефекта, и оба воспроизводятся только на гонке, поэтому глазами их
// не видно:
//
// 1. Рассылка не знала об окончании матча. На дуэли подписан 231 человек, пауза
//    60 мс — полный круг идёт около 30 секунд, а дуэль принимают за секунды. Бот
//    продолжал звать людей в матч, которого уже нет.
//
// 2. Ветка 'removed' читала список сообщений, удаляла их, а затем стирала ВСЕ строки
//    матча одним DELETE ... WHERE match_id = ?. Строки, дописанные рассылкой за те
//    же секунды, стирались, ни разу не будучи удалёнными из Telegram. Учёт пустел,
//    сообщения оставались, уборщик их уже не находил — висели навсегда.
//
// ⚠️ Тест проверяет ИСХОДНИК, а не поведение: зависимостей бота (grammy,
// better-sqlite3) в репозитории нет, поднимать их ради одной проверки дороже, чем
// зафиксировать инварианты. Поэтому утверждения ниже намеренно узкие — они ловят
// именно те две конструкции, которые ломались. Если watchDuels перепишут на другую
// схему уборки, тест надо переписать под неё, а не ослабить.

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const source = fs.readFileSync(
    path.resolve(__dirname, '..', 'server', 'bot', 'src', 'bot.js'),
    'utf8'
);

// Комментарии вырезаем: иначе объяснительный текст выше сам себя «подтвердит».
// Ровно на этом обжигался страж полей состояния — давал ложное «всё хорошо».
const stripComments = src => src
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');

const code = stripComments(source);

const start = code.indexOf('function watchDuels()');
assert.ok(start >= 0, 'watchDuels не найдена — проверять нечего');
const sweeperAt = code.indexOf('const DUEL_MSG_STALE_MS');
assert.ok(sweeperAt > start, 'Уборщик протухших вызовов пропал — без него огрехи рассылки копятся навсегда');
const watch = code.slice(start, sweeperAt);

// ─── Дефект 2: массовое стирание строк ───────────────────────────────────────
// Именно эта строка осиротила сообщения. Строку удаляем ПОШТУЧНО — ту, чьё
// сообщение только что обработали.
assert.doesNotMatch(watch, /DELETE FROM duel_msgs WHERE match_id/,
    'Вернулось стирание всех строк матча одним DELETE. Оно стирает и те строки, что '
    + 'рассылка дописала во время уборки: сообщения останутся у людей навсегда, '
    + 'а уборщик их не найдёт — учёт уже пуст.');

assert.match(watch, /DELETE FROM duel_msgs WHERE rowid = \?/,
    'Пропало поштучное удаление строки по rowid — без него уборка не может быть точной');

// ─── Дефект 1: рассылка в мёртвый матч ───────────────────────────────────────
const sendAt = watch.indexOf('sendSafe(id,');
assert.ok(sendAt >= 0, 'Не найдена отправка вызова на дуэль');
const loopHead = watch.lastIndexOf('for (const { id } of candidates)', sendAt);
assert.ok(loopHead >= 0, 'Не найден цикл рассылки по подписчикам');

const beforeSend = watch.slice(loopHead, sendAt);
assert.match(beforeSend, /if \(!waiting\.has\(matchId\)\) break;/,
    'Рассылка снова не проверяет, жив ли матч. Круг занимает ~30 секунд, дуэль '
    + 'принимают за секунды — без этой проверки большинство получит приглашение '
    + 'в несуществующий матч, и висеть оно будет до уборщика.');
assert.match(beforeSend, /Date\.now\(\) - createdAt > MAX_WAITING_AGE_MS\) break;/,
    'Пропала возрастная страховка в цикле: если событие об окончании матча потеряется '
    + '(перезапуск бота, обрыв опроса), рассылка пойдёт по всему списку в мёртвый матч');

// ─── Порядок в ветке «матч закончился» ───────────────────────────────────────
const removedAt = watch.indexOf("change.type === 'removed'");
assert.ok(removedAt >= 0, 'Пропала ветка обработки окончания матча');
const removedBlock = watch.slice(removedAt);
const stopAt = removedBlock.indexOf('waiting.delete(matchId)');
const purgeAt = removedBlock.indexOf('purgeMatchMessages(matchId)');
assert.ok(stopAt >= 0, 'Окончание матча больше не обрывает рассылку');
assert.ok(purgeAt >= 0, 'Окончание матча больше не убирает разосланные вызовы');
assert.ok(stopAt < purgeAt,
    'Уборка запускается РАНЬШЕ остановки рассылки. Тогда цикл продолжит слать '
    + 'сообщения нам за спиной, и убирать их будет уже некому.');

// ─── Волны вместо ковровой рассылки ──────────────────────────────────────────
// Дуэли нужен ОДИН соперник, а подписано 231 человек. Полный обход давал ~200
// сообщений на матч, которые потом приходилось догонять удалением: 209 удалений за
// день, круг ~30 секунд, и любой сбой в уборке оставлял вызовы висеть.
// Правильно не создавать двести сообщений там, где хватает десятка.
assert.match(code, /DUEL_WAVE_SIZE = \d+/, 'Пропал размер волны приглашений');
assert.match(code, /DUEL_WAVE_PAUSE_MS = \d+/, 'Пропала пауза между волнами');
assert.match(watch, /notify_duel = 1 ORDER BY RANDOM\(\)/,
    'Порядок обхода снова не случайный: первые по id получали бы каждый вызов, а хвост — никогда');
assert.match(watch, /if \(\+\+inWave >= DUEL_WAVE_SIZE\)/,
    'Рассылка снова идёт сплошным списком, без волн — это возвращает двести сообщений на матч');
// Пауза обязана быть дробной: один сон на всю паузу задержал бы обрыв, и улетела бы
// лишняя волна уже в законченный матч.
assert.match(watch, /for \(let waited = 0; waited < DUEL_WAVE_PAUSE_MS; waited \+= \d+\) \{\s*\n\s*if \(!waiting\.has\(matchId\)\) break;/,
    'Пауза между волнами не проверяет, жив ли матч, — лишняя волна уйдёт в законченную дуэль');

// ─── Отказы Telegram обязаны быть слышны ─────────────────────────────────────
// Раньше здесь стоял пустой catch: сколько вызовов реально осталось висеть у людей,
// узнать было неоткуда — жалобу пришлось ловить со слов ученика.
assert.match(watch, /console\.warn\(`duel cleanup:/,
    'Отказы удаления снова молчат. Пустой catch здесь означает, что о висящих '
    + 'у людей вызовах мы узнаем только из жалоб.');

console.log('duel-cleanup: ok (рассылка обрывается на конце матча, строки удаляются поштучно, отказы видны)');
