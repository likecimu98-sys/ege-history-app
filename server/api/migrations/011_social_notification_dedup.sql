-- Ключ повтора у уведомлений предмета.
--
-- Зачем. Единственная защита от дубля была частичным уникальным индексом по
-- паре (assignment_id, telegram_id): «одно ДЗ — одно сообщение ученику». Для
-- нового уведомления «ученик сдал» этого мало и даже вредно: получатель у всех
-- таких сообщений один — учитель, и пара (задание, учитель) разрешила бы РОВНО
-- ОДНО сообщение на всё задание. Учитель узнал бы про первого сдавшего и
-- никогда — про остальных двадцать девять.
--
-- Общий ключ решает это без исключений: строку формирует тот, кто ставит
-- задачу в очередь, и он же решает, что считать повтором. Для «ученик сдал»
-- это «задание + ученик».
--
-- Индекс частичный: у старых записей ключ пустой, и под ограничение они не
-- попадают. Прежний индекс по (assignment_id, telegram_id) остаётся на месте и
-- продолжает беречь рассылку о выдаче.

BEGIN;

ALTER TABLE social_notification_jobs
  ADD COLUMN IF NOT EXISTS dedup_key text NOT NULL DEFAULT '';

CREATE UNIQUE INDEX IF NOT EXISTS social_notification_jobs_dedup_uq
  ON social_notification_jobs(dedup_key)
  WHERE dedup_key <> '';

COMMIT;
