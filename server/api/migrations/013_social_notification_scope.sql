-- Уникальность рассылки о ВЫДАЧЕ не должна ловить уведомления о СДАЧЕ.
--
-- 🔴 ЧТО СЛОМАЛОСЬ. Индекс из 006 запрещает две строки на пару
-- (задание, telegram). Он писался под одно правило: «одно ДЗ — одно сообщение
-- ученику». Но у уведомления «ученик сдал» получатель один на всех — учитель,
-- и пара (задание, учитель) разрешает РОВНО ОДНУ такую строку на всё задание.
-- Миграция 011 завела для этого отдельный dedup_key и оставила старый индекс
-- «беречь рассылку о выдаче» — вот только он продолжал действовать и на новые
-- строки тоже.
--
-- Итог был хуже, чем потерянное уведомление. Вставка сдачи указывает арбитром
-- ТОЛЬКО dedup_key, поэтому нарушение старого индекса не гасится, а
-- поднимается как ошибка 23505 — внутри транзакции, которая сохраняет ответы
-- ученика. Postgres обрывает транзакцию целиком, следующий запрос падает с
-- 25P02, запрос отвечает 500, клиент честно оставляет очередь на потом — и
-- застревает навсегда. 27.08.2026 ученица так решила 31 задание: все они
-- остались в очереди её телефона, учитель не увидел ни одного, а
-- пересинхронизация повторяла ту же ошибку каждые полминуты. Достаточно было
-- одноклассника, сдавшего ту же домашку раньше.
--
-- Поэтому старый индекс сужается до строк без ключа повтора: у рассылки о
-- выдаче dedup_key пуст, и её защита сохраняется дословно, а всё, что завело
-- свой ключ, отвечает за дубли этим ключом и только им.

BEGIN;

DROP INDEX IF EXISTS social_notification_jobs_assignment_uq;

CREATE UNIQUE INDEX IF NOT EXISTS social_notification_jobs_assignment_uq
  ON social_notification_jobs(assignment_id, telegram_id)
  WHERE assignment_id IS NOT NULL AND dedup_key = '';

COMMIT;
