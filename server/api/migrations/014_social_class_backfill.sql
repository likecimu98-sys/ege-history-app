-- Что получает ученик, вступивший в класс ПОСЛЕ выдачи домашки.
--
-- До сих пор — всё. Запросы выдачи сравнивали только «состоит в классе» и
-- «домашка активна», даты входа не касались вовсе. Для курса, идущего по
-- темам, это верно: пришедший в ноябре должен получить хвост с сентября. Для
-- класса, где домашка — это работа к конкретному уроку, это мусор: новичок
-- получает пачку чужих работ, часть сразу красными «срок прошёл», и тянет вниз
-- успешность класса в таблице учителя.
--
-- Правило выбирает учитель, и выбирает у КЛАССА, а не у каждой работы: это
-- свойство того, как он ведёт группу.
--   all   — все ранее выданные (прежнее поведение);
--   undue — только те, срок которых на момент входа ещё не прошёл;
--   new   — только выданные после входа.
--
-- 🔴 Умолчание 'undue' — В ТОМ ЧИСЛЕ для уже существующих классов. Это меняет
-- то, что ученики видят прямо сейчас, поэтому проверено на живых данных: под
-- правило попадал ровно один ученик, и его спасает оговорка «уже работал»
-- (см. ASSIGNMENT_VISIBLE_SQL в store.js). Домашка, по которой у ученика есть
-- прогресс, не прячется НИКОГДА: иначе с экрана исчезла бы его собственная
-- сделанная работа.

BEGIN;

ALTER TABLE social_classes
  ADD COLUMN IF NOT EXISTS backfill text NOT NULL DEFAULT 'undue';

ALTER TABLE social_classes
  DROP CONSTRAINT IF EXISTS social_classes_backfill_check;

ALTER TABLE social_classes
  ADD CONSTRAINT social_classes_backfill_check CHECK (backfill IN ('all', 'undue', 'new'));

COMMIT;
